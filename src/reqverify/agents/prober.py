"""Sandboxed probe runner for Agent 3 (Guide §9 Agent 3 Probe, NFR-05).

Runs one LLM-written pytest-playwright script in a *subprocess* with a hard timeout, collects the
classification written by :mod:`reqverify.plugins.probe_reporter`, and keeps a Playwright trace archive
as audit evidence. The script is statically validated first and never executed if unsafe.

Isolation applied here: separate process + temp working directory, hard timeout with process-tree kill,
Anthropic API key stripped from the child environment, credentials supplied through fixtures built from
config (never through prompts). Network isolation to the SUT only is *not* enforced at OS level; run the
pipeline in the Docker network described in Phase 08 for that.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import tempfile
import time
from pathlib import Path
from typing import Dict, Mapping, Optional

from reqverify.plugins.probe_reporter import RESULT_PATH_ENV
from reqverify.safety.ast_validator import validate_script_ast
from reqverify.schemas.contracts import ProbeResult

STDOUT_TAIL_CHARS = 2000
CRED_ENV_PREFIX = "REQVERIFY_CRED_"

_CONFTEST = '''"""Generated by ReqVerify prober: exposes SUT credentials as fixtures (kept out of LLM prompts)."""
import json
import os
import pytest


def _cred(name):
    return json.loads(os.environ.get("REQVERIFY_CRED_" + name.upper(), "{}"))


@pytest.fixture
def test_user():
    return _cred("test_user")


@pytest.fixture
def admin_user():
    return _cred("admin_user")
'''


def default_credentials() -> Dict[str, Dict[str, str]]:
    """Seeded SUT credentials from the environment (.env.example), never from prompts."""
    return {
        "test_user": {
            "email": os.getenv("TECHSTORE_TEST_USER_EMAIL", "testuser@example.com"),
            "password": os.getenv("TECHSTORE_TEST_USER_PASSWORD", "Password123!"),
        },
        "admin_user": {
            "email": os.getenv("TECHSTORE_ADMIN_USER_EMAIL", "admin@example.com"),
            "password": os.getenv("TECHSTORE_ADMIN_USER_PASSWORD", "AdminPass123!"),
        },
    }


def build_child_env(credentials: Mapping[str, Mapping[str, str]], result_path: Optional[str] = None) -> Dict[str, str]:
    """Environment for the probe subprocess: parent env minus secrets, plus credential fixtures."""
    env = {k: v for k, v in os.environ.items() if k != "ANTHROPIC_API_KEY" and not k.endswith("_API_KEY")}
    for name, value in credentials.items():
        env[CRED_ENV_PREFIX + name.upper()] = json.dumps(dict(value))
    if result_path:
        env[RESULT_PATH_ENV] = result_path
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    return env


def _kill_process_tree(pid: int) -> None:
    if os.name == "nt":
        subprocess.run(["taskkill", "/F", "/T", "/PID", str(pid)], capture_output=True, check=False)
    else:  # pragma: no cover - POSIX path
        import signal

        try:
            os.killpg(os.getpgid(pid), signal.SIGKILL)
        except ProcessLookupError:
            pass


class TestProber:
    """Executes one generated test script and returns execution evidence as a :class:`ProbeResult`."""

    __test__ = False  # not a pytest test class

    def __init__(
        self,
        base_url: str,
        run_id: str = "dev",
        traces_root: Path | str = "traces",
        timeout_s: float = 60.0,
        credentials: Optional[Mapping[str, Mapping[str, str]]] = None,
        browser: str = "chromium",
    ):
        self.base_url = base_url
        self.run_id = run_id
        self.traces_root = Path(traces_root)
        self.timeout_s = timeout_s
        self.credentials = dict(credentials) if credentials is not None else default_credentials()
        self.browser = browser

    def probe(self, script: str, condition_id: str, iteration: int = 1) -> ProbeResult:
        validate_script_ast(script)  # raises ScriptSafetyViolation; nothing runs if unsafe

        evidence_dir = (self.traces_root / self.run_id / condition_id / f"iter-{iteration}").resolve()
        evidence_dir.mkdir(parents=True, exist_ok=True)
        (evidence_dir / "script.py").write_text(script, encoding="utf-8")

        with tempfile.TemporaryDirectory(prefix="reqverify_probe_") as tmp:
            workdir = Path(tmp)
            (workdir / "test_probe.py").write_text(script, encoding="utf-8")
            (workdir / "conftest.py").write_text(_CONFTEST, encoding="utf-8")
            result_path = workdir / "probe_result.json"
            output_dir = evidence_dir / "playwright"

            cmd = [
                sys.executable, "-m", "pytest", "test_probe.py",
                "-p", "reqverify.plugins.probe_reporter",
                "-p", "no:cacheprovider",
                "--rootdir", str(workdir),
                "--base-url", self.base_url,
                "--browser", self.browser,
                "--tracing", "on",
                "--output", str(output_dir),
                "-x", "-q", "--tb=short", "--no-header",
            ]
            popen_kwargs: dict = {}
            if os.name == "nt":
                popen_kwargs["creationflags"] = subprocess.CREATE_NEW_PROCESS_GROUP
            else:  # pragma: no cover
                popen_kwargs["start_new_session"] = True

            start = time.monotonic()
            proc = subprocess.Popen(
                cmd,
                cwd=workdir,
                env=build_child_env(self.credentials, str(result_path)),
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                encoding="utf-8",
                errors="replace",
                **popen_kwargs,
            )
            timed_out = False
            try:
                output, _ = proc.communicate(timeout=self.timeout_s)
            except subprocess.TimeoutExpired:
                timed_out = True
                _kill_process_tree(proc.pid)
                try:
                    output, _ = proc.communicate(timeout=10)
                except subprocess.TimeoutExpired:  # pragma: no cover
                    output = ""
            duration = time.monotonic() - start

            traces = sorted(output_dir.rglob("trace.zip")) if output_dir.exists() else []
            trace_path = str(traces[0]) if traces else None
            tail = (output or "")[-STDOUT_TAIL_CHARS:]

            if timed_out:
                return ProbeResult(
                    exit_code=-1, outcome="timeout", exception_type="TimeoutExpired",
                    stdout_tail=tail, duration_s=duration, trace_path=trace_path,
                )

            if result_path.exists():
                report = json.loads(result_path.read_text(encoding="utf-8"))
                message = report.get("message") or ""
                return ProbeResult(
                    exit_code=proc.returncode,
                    outcome=report["outcome"],
                    exception_type=report.get("exception_type"),
                    stdout_tail=(message + "\n" + tail)[-STDOUT_TAIL_CHARS:] if message else tail,
                    duration_s=duration,
                    trace_path=trace_path,
                )

            # No JSON written: collection/import error or interpreter crash before the test body ran.
            return ProbeResult(
                exit_code=proc.returncode,
                outcome="passed" if proc.returncode == 0 else "runtime_error",
                exception_type=None if proc.returncode == 0 else "CollectionError",
                stdout_tail=tail, duration_s=duration, trace_path=trace_path,
            )
